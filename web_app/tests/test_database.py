def test_database_initializes():
    """Verify that the configured database initializes successfully."""
    app.init_db()

    conn = app.db_connect()
    try:
        customers = conn.execute(
            "SELECT COUNT(*) AS count FROM customers"
        ).fetchone()

        outreach = conn.execute(
            "SELECT COUNT(*) AS count FROM outreach_log"
        ).fetchone()

        assert customers is not None
        assert outreach is not None
    finally:
        conn.close()


def test_postgres_placeholder_conversion():
    """Test placeholder conversion without connecting to Neon."""
    from app import DatabaseConnection

    class FakeCursor:
        def __init__(self):
            self.sql = None
            self.params = None

        def execute(self, sql, params):
            self.sql = sql
            self.params = params
            return self

    class FakeConnection:
        def __init__(self):
            self.cursor = FakeCursor()

        def execute(self, sql, params):
            return self.cursor.execute(sql, params)

        def close(self):
            pass

    fake = FakeConnection()
    conn = DatabaseConnection(fake, postgres=True)

    conn.execute(
        "SELECT * FROM customers WHERE id = ? AND email = ?",
        (10, "demo@example.com")
    )

    assert fake.cursor.sql == (
        "SELECT * FROM customers WHERE id = %s AND email = %s"
    )
    assert fake.cursor.params == (10, "demo@example.com")


def test_postgres_schema_generation(monkeypatch):
    """Verify PostgreSQL schema SQL without connecting to a database."""
    import app

    class FakeConnection:
        def __init__(self):
            self.statements = []

        def __enter__(self):
            return self

        def __exit__(self, exc_type, exc, tb):
            return False

        def execute(self, sql, params=()):
            self.statements.append(sql)
            return self

    fake = FakeConnection()

    monkeypatch.setattr(app, "USE_POSTGRES", True)
    monkeypatch.setattr(app, "db_connect", lambda: fake)

    app.init_db()

    assert len(fake.statements) == 2

    customers_sql = fake.statements[0]
    outreach_sql = fake.statements[1]

    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in customers_sql
    assert "DOUBLE PRECISION" in customers_sql
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in outreach_sql
    assert "FOREIGN KEY(customer_id) REFERENCES customers(id)" in outreach_sql


def test_postgres_customer_crud():
    import app

    assert app.USE_POSTGRES is True

    with app.db_connect() as conn:
        conn.execute("""
            INSERT INTO customers (
                external_id, gender, senior, partner, dependents,
                tenure, phone_service, internet, security, tech,
                streaming, contract, paperless, payment, monthly, total,
                churn_probability, risk_level, revenue_at_risk,
                priority_score, recovery_action, recovery_message,
                created_at, updated_at
            ) VALUES (
                ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
                ?, ?, ?, ?, ?, ?, ?, ?
            )
        """, (
            "TEST-CRUD-001", "Female", "0", "No", "No",
            12, "Yes", "DSL", "No", "No", "No",
            "Month-to-month", "Yes", "Electronic check",
            50.0, 600.0, 0.5, "Medium", 25.0, 50.0,
            "Test action", "Test message", "2026-10-31", "2026-10-31"
        ))

        row = conn.execute(
            "SELECT * FROM customers WHERE external_id = ?",
            ("TEST-CRUD-001",)
        ).fetchone()

        assert row["external_id"] == "TEST-CRUD-001"

        conn.execute(
            "UPDATE customers SET outreach_status = ? WHERE external_id = ?",
            ("Approved", "TEST-CRUD-001")
        )

        updated = conn.execute(
            "SELECT outreach_status FROM customers WHERE external_id = ?",
            ("TEST-CRUD-001",)
        ).fetchone()

        assert updated["outreach_status"] == "Approved"

        conn.execute(
            "DELETE FROM customers WHERE external_id = ?",
            ("TEST-CRUD-001",)
        )


def test_postgres_csv_import():
    import io
    from werkzeug.datastructures import FileStorage

    assert app.USE_POSTGRES is True

    csv_data = (
        "customerID,gender,SeniorCitizen,Partner,Dependents,tenure,"
        "PhoneService,InternetService,OnlineSecurity,TechSupport,"
        "StreamingTV,Contract,PaperlessBilling,PaymentMethod,"
        "MonthlyCharges,TotalCharges\n"
        "TEST-CSV-001,Female,0,Yes,No,12,Yes,DSL,No,No,"
        "No,Month-to-month,Yes,Electronic check,50,600\n"
    )

    uploaded = FileStorage(
        stream=io.BytesIO(csv_data.encode("utf-8")),
        filename="test_customers.csv"
    )

    inserted, total, errors = app.import_customer_csv(uploaded)

    assert inserted == 1, errors
    assert total == 1

    with app.db_connect() as conn:
        row = conn.execute(
            "SELECT * FROM customers WHERE external_id = ?",
            ("TEST-CSV-001",)
        ).fetchone()

        assert row is not None
        assert row["source"] == "CSV import"

        conn.execute(
            "DELETE FROM customers WHERE external_id = ?",
            ("TEST-CSV-001",)
        )


