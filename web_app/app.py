class DatabaseConnection:
    """Compatibility wrapper for SQLite and PostgreSQL."""

    def __init__(self, raw, postgres=False):
        self.raw = raw
        self.postgres = postgres

    def __enter__(self):
        self.raw.__enter__()
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            return self.raw.__exit__(exc_type, exc, tb)
        finally:
            self.raw.close()

    def execute(self, sql, params=()):
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.raw.execute(sql, params)

    def close(self):
        return self.raw.close()



def db_connect():
    """Use Neon/PostgreSQL when DATABASE_URL is set; otherwise use local SQLite."""
    if USE_POSTGRES:
        url = DATABASE_URL
        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://"):]
        raw = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)
        return DatabaseConnection(raw, postgres=True)
    os.makedirs(os.path.dirname(os.path.abspath(DATABASE_PATH)), exist_ok=True)
    raw = sqlite3.connect(DATABASE_PATH)
    raw.row_factory = sqlite3.Row
    raw.execute("PRAGMA foreign_keys = ON")
    return DatabaseConnection(raw, postgres=False)


